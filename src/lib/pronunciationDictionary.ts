/**
 * Apply dictionary replacements to Japanese text to ensure correct TTS pronunciation.
 */
export function applyPronunciationReplacements(text: string): string {
    let result = text;

    // First remove bracketed furigana if present, e.g. 浅草寺(せんそうじ) -> せんそうじ
    result = result.replace(/([一-龠]+)\(([ぁ-んァ-ヶー]+)\)/g, "$2");

    // Sort keys by length descending so longer compound phrases (e.g. "清水の舞台") match before "清水寺"
    const sortedKeys = Object.keys(PRONUNCIATION_DICT).sort((a, b) => b.length - a.length);

    for (const key of sortedKeys) {
        if (result.includes(key)) {
            const val = PRONUNCIATION_DICT[key];
            result = result.replaceAll(key, val);
        }
    }

    return result;
}
